"""Export completed CodeAnt results and apply the example's explicit CI policy."""

import argparse
import csv
import json
import os
from collections import Counter
from pathlib import Path
from xml.sax.saxutils import escape


def load_results():
    result = json.loads(Path("results.json").read_text())
    if result.get("status") != "COMPLETED":
        raise ValueError("Scan did not complete; refusing to treat missing results as clean")
    findings = result.get("findings")
    if not isinstance(findings, list):
        raise ValueError("Completed result must contain a findings list")
    metrics = result.get("metrics", {})
    for metric in ("sast_rating_full_code", "sca_rating_full_code"):
        if metric not in metrics:
            raise ValueError(f"Missing required scan metric: {metric}")
    for finding in findings:
        if not isinstance(finding, dict) or not finding.get("engine"):
            raise ValueError("Malformed finding")
    return result


def policy_result(result, scanner):
    policy = json.loads(Path(__file__).with_name("policy.json").read_text())[scanner]
    selected = [item for item in result["findings"] if item["engine"] == scanner]
    severities = policy["severities"]
    # An unknown severity must not silently evade an enforcement policy.
    known = {"INFO", "INFORMATIONAL", "LOW", "MEDIUM", "MODERATE", "HIGH", "CRITICAL"}
    blocking = [item for item in selected if "*" in severities
                or str(item.get("severity", "")).upper() in severities
                or str(item.get("severity", "")).upper() not in known]
    limit = policy["max_findings"]
    return len(blocking) > limit, f"{scanner}: {len(blocking)} blocking findings; allowed={limit}"


def csv_cell(value):
    text = "" if value is None else str(value)
    # Findings are untrusted content; prevent spreadsheet formula evaluation.
    return "'" + text if text.lstrip().startswith(("=", "+", "-", "@")) else text


def export(result):
    from reportlab.lib import colors
    from reportlab.lib.styles import getSampleStyleSheet
    from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle

    fields = ["engine", "severity", "file", "line", "rule", "message"]
    with Path("codeant-findings.csv").open("w", newline="") as output:
        writer = csv.writer(output)
        writer.writerow(fields)
        writer.writerows([csv_cell(item.get(key)) for key in fields] for item in result["findings"])

    context = {"repository": os.getenv("GITHUB_REPOSITORY", "local"),
               "commit": os.getenv("SCAN_COMMIT", os.getenv("GITHUB_SHA", "local")),
               "run_url": os.getenv("GITHUB_SERVER_URL", "https://github.com") + "/"
               + os.getenv("GITHUB_REPOSITORY", "local") + "/actions/runs/"
               + os.getenv("GITHUB_RUN_ID", "local")}
    Path("codeant-run.json").write_text(json.dumps(context, indent=2) + "\n")
    styles = getSampleStyleSheet()
    story = [Paragraph("CodeAnt CI security scan", styles["Title"])]
    for key, value in context.items():
        story.append(Paragraph(escape(f"{key}: {value}"), styles["BodyText"]))
    story += [Spacer(1, 16), Paragraph("Example policy results", styles["Heading2"])]
    rows = [["Scanner", "Total findings", "Policy verdict"]]
    counts = Counter(item["engine"] for item in result["findings"])
    for scanner in ("secrets", "sast", "sca"):
        failed, message = policy_result(result, scanner)
        rows.append([scanner, str(counts[scanner]), "FAILED" if failed else "PASSED"])
        print(message)
    table = Table(rows, colWidths=[140, 140, 160], repeatRows=1)
    table.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e9e9ff")),
                               ("GRID", (0, 0), (-1, -1), 0.5, colors.lightgrey),
                               ("BOTTOMPADDING", (0, 0), (-1, -1), 10),
                               ("TOPPADDING", (0, 0), (-1, -1), 10)]))
    story += [table, Spacer(1, 16), Paragraph("Scope and interpretation", styles["Heading2"]),
              Paragraph("Full repository results for secrets, SAST and SCA. This summary and the CSV "
                        "are generated by the example workflow. The policy is defined in policy.json; "
                        "it is separate from the native CodeAnt quality-gate verdict.", styles["BodyText"]),
              Paragraph(escape("Native CodeAnt verdict: " + str(result.get("quality_gate_status"))), styles["BodyText"]),
              Paragraph("See codeant-findings.csv for all findings and the Actions logs for runner diagnostics.", styles["BodyText"])]
    SimpleDocTemplate("codeant-summary.pdf", title="CodeAnt CI security scan").build(story)
    print("Completed scan; wrote codeant-findings.csv, codeant-summary.pdf, codeant-run.json")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("operation", choices=["export", "gate"])
    parser.add_argument("--scanner", choices=["secrets", "sast", "sca"])
    parser.add_argument("--mode", choices=["warn", "enforce"], default="enforce")
    args = parser.parse_args()
    try:
        result = load_results()
        if args.operation == "export":
            export(result)
            return 0
        if not args.scanner:
            parser.error("gate requires --scanner")
        failed, message = policy_result(result, args.scanner)
        print(f"{message}; mode={args.mode}")
        summary = os.getenv("GITHUB_STEP_SUMMARY")
        if summary:
            with open(summary, "a") as output:
                output.write(f"### {args.scanner} policy\n\n{message}; mode={args.mode}\n")
        if failed:
            level = "warning" if args.mode == "warn" else "error"
            print(f"::{level}::{message}")
        return int(failed and args.mode == "enforce")
    except (OSError, ValueError, KeyError, TypeError) as error:
        print(f"::error::Invalid or missing scan results: {error}")
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
